// Test with proper Data section encoding
// Data section format for active segment:
// flags=1 (active, memory index 0), offset=init_expr, data=vec(byte)

const wasm1 = new Uint8Array([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, // header
    // Type
    0x01, 0x04, 0x01, 0x60, 0x00, 0x00,
    // Function
    0x03, 0x02, 0x01, 0x00,
    // Memory: count=1, flags=0, initial=1 page
    0x05, 0x04, 0x03, 0x01, 0x00, 0x01,
    // Export
    0x07, 0x08, 0x01, 0x04, 0x6d, 0x61, 0x69, 0x6e, 0x00, 0x00,
    // Code
    0x0a, 0x04, 0x01, 0x02, 0x00, 0x0b,
    // Data: count=1, flags=1 (active, memory 0), offset=i32.const(0), data
    0x0b, 0x0c, 0x01, 0x41, 0x00, 0x0b, 0x05, 0x48, 0x65, 0x6c, 0x6c, 0x6f
]);

console.log('With Data section:');
console.log('  Valid:', WebAssembly.validate(wasm1) ? 'Valid' : 'Invalid');
if (!WebAssembly.validate(wasm1)) {
    WebAssembly.compile(wasm1).catch(e => console.log('  Error:', e.message.split('\n')[0]));
} else {
    WebAssembly.compile(wasm1).then(m => {
        console.log('  Compile OK');
        const inst = new WebAssembly.Instance(m);
        console.log('  Instance OK');
    });
}

